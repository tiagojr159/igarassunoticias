<script>
  const lb = document.getElementById('lb');
  const lbImg = document.getElementById('lbImg');
  const lbCap = document.getElementById('lbCap');
  const lbClose = document.getElementById('lbClose');
  const lbOpen = document.getElementById('lbOpen');

  function openLightbox(src, cap) {
    lbImg.src = src;
    lbImg.alt = cap || '';
    lbCap.textContent = cap || '';
    lbOpen.href = src;
    lb.classList.add('show');
    document.body.style.overflow = 'hidden';
  }

  function closeLightbox() {
    lb.classList.remove('show');
    lbImg.src = '';
    document.body.style.overflow = '';
  }

  document.addEventListener('click', (e) => {
    const shot = e.target.closest('.shot');
    if (shot) {
      const src = shot.getAttribute('data-src');
      const cap = shot.getAttribute('data-cap');
      openLightbox(src, cap);
    }
  });

  lbClose.addEventListener('click', closeLightbox);
  lb.addEventListener('click', (e) => {
    if (e.target === lb) closeLightbox();
  });
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeLightbox();
  });

  // filtro de categoria (somente fotos do portfólio)
  const catSelect = document.getElementById('catSelect');
  const gallery = document.getElementById('gallery');
  const countShots = document.getElementById('countShots');

  function updateCount() {
    const visible = [...gallery.querySelectorAll('.shot')].filter(el => el.style.display !== 'none').length;
    countShots.textContent = visible;
  }

  function filterGallery() {
    const val = catSelect.value;
    gallery.querySelectorAll('.shot').forEach(el => {
      const cat = el.getAttribute('data-cat');
      el.style.display = (val === '__all__' || cat === val) ? '' : 'none';
    });
    updateCount();
  }

  catSelect.addEventListener('change', filterGallery);
  filterGallery();
</script>

